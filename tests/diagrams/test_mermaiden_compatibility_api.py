def test_browser_mermaid_runtime_matches_mermaiden_compatibility_version() -> None:
    package = json.loads((Path(__file__).parents[2] / "browser" / "package.json").read_text())
    renderer_package = json.loads((Path(__file__).parents[2] / "package.json").read_text())

    with Application.create() as application:
        mermaiden_version = application.mermaid_version
        mermaiden_cli_version = application.mermaid_cli_version

    assert package["dependencies"]["mermaid"] == mermaiden_version
    assert renderer_package["devDependencies"] == {
        "@mermaid-js/mermaid-cli": mermaiden_cli_version,
        "mermaid": mermaiden_version,
    }


def test_mermaiden_11_0_1_snapshot_migrates_to_v9_through_the_public_api() -> None:
    fixture = json.loads((Path(__file__).parent / "fixtures" / "mermaiden-11.0.1-flowchart-v8.json").read_text())
    assert fixture["package_version"] == "11.0.1"

    diagram_set_model = apps.get_model("diagrams", "DiagramSet")
    diagram_model = apps.get_model("diagrams", "Diagram")
    diagram_set = diagram_set_model.objects.create(
        title="Persisted 11.0.1 snapshot",
        description="Compatibility fixture generated by Mermaiden 11.0.1.",
    )
    diagram = diagram_model.objects.create(
        diagram_set=diagram_set,
        title="Persisted 11.0.1 snapshot",
        kind="flowchart",
        snapshot=fixture["snapshot"],
        source=fixture["source"],
    )
    migration = import_module("enclosure.diagrams.migrations.0006_upgrade_mermaiden_13_snapshots")
    migration.upgrade_snapshots(apps, connection.schema_editor())

    client = Client()
    restored = client.get(f"/api/diagrams/{diagram.pk}")

    assert restored.status_code == 200
    stored = restored.json()
    fields = stored["snapshot"]["configuration"]["fields"]
    assert stored["snapshot"]["version"] == 9
    assert stored["snapshot"]["draft"] is True
    assert stored["source"] == ""
    assert "default_renderer" not in fields
    assert fields["layout"]["fields"]["root"] == "dagre"
    assert fields["wrapping_width"] == 200.0
    assert fields["min_node_width"] == 120.0



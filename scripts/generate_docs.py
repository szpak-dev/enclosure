import os
import sys
from dataclasses import dataclass
from pathlib import Path

import django
from pydantic import BaseModel, ConfigDict, Field


class OpenApiOperation(BaseModel):
    model_config = ConfigDict(extra="ignore", populate_by_name=True)

    operation_id: str = Field(alias="operationId")
    summary: str
    tags: tuple[str, ...] = Field(min_length=1)


class OpenApiComponents(BaseModel):
    model_config = ConfigDict(extra="ignore")

    schemas: dict[str, object] = Field(default_factory=dict)


class OpenApiDocument(BaseModel):
    model_config = ConfigDict(extra="ignore")

    paths: dict[str, dict[str, object]]
    components: OpenApiComponents = Field(default_factory=OpenApiComponents)


@dataclass(frozen=True)
class OperationReference:
    tag: str
    method: str
    path: str
    operation_id: str
    summary: str


@dataclass(frozen=True)
class OpenApiLoader:
    def load(self) -> OpenApiDocument:
        os.environ.setdefault("DJANGO_SETTINGS_MODULE", "enclosure.core.settings")
        django.setup()
        from enclosure.core.api import openapi_schema

        return OpenApiDocument.model_validate(openapi_schema)


@dataclass(frozen=True)
class OpenApiReferenceRenderer:
    methods: tuple[str, ...] = ("get", "post", "put", "patch", "delete")

    def render(self, document: OpenApiDocument) -> str:
        operations = self.operations(document)
        lines = [
            "# API operations",
            "",
            "<!-- Generated by scripts/generate_docs.py. Do not edit by hand. -->",
            "",
            "This reference is generated from the OpenAPI contract in the checked-out Enclosure source.",
            "Operation IDs relate REST operations, Siren actions, and generated MCP tools when the interface exposes",
            "that operation.",
            "",
        ]
        for tag in sorted({operation.tag for operation in operations}):
            lines.extend(
                (
                    f"## {tag}",
                    "",
                    "| Method | Path | Operation ID | Summary |",
                    "| --- | --- | --- | --- |",
                )
            )
            lines.extend(self.row(operation) for operation in operations if operation.tag == tag)
            lines.append("")
        lines.extend(("## Schemas", "", "The OpenAPI components define these named transport schemas:", ""))
        lines.extend(f"- `{name}`" for name in sorted(document.components.schemas))
        lines.append("")
        return "\n".join(lines)

    def operations(self, document: OpenApiDocument) -> tuple[OperationReference, ...]:
        result: list[OperationReference] = []
        for path, path_item in sorted(document.paths.items()):
            for method in self.methods:
                if method not in path_item:
                    continue
                operation = OpenApiOperation.model_validate(path_item[method])
                result.append(
                    OperationReference(
                        tag=operation.tags[0],
                        method=method.upper(),
                        path=path,
                        operation_id=operation.operation_id,
                        summary=operation.summary,
                    )
                )
        return tuple(result)

    def row(self, operation: OperationReference) -> str:
        summary = operation.summary.replace("|", "\\|").replace("\n", " ")
        return f"| `{operation.method}` | `{operation.path}` | `{operation.operation_id}` | {summary} |"


@dataclass(frozen=True)
class DocumentationGenerationCommand:
    root: Path

    def run(self, arguments: tuple[str, ...]) -> int:
        if arguments not in ((), ("--check",)):
            print("Usage: generate_docs.py [--check]", file=sys.stderr)
            return 2
        target = self.root / "docs" / "reference" / "api.md"
        rendered = OpenApiReferenceRenderer().render(OpenApiLoader().load())
        if arguments == ("--check",):
            if not target.is_file() or target.read_text(encoding="utf-8") != rendered:
                print(f"Generated documentation is stale: {target.relative_to(self.root)}", file=sys.stderr)
                return 1
            print(f"Generated documentation is current: {target.relative_to(self.root)}")
            return 0
        target.write_text(rendered, encoding="utf-8")
        print(f"Generated {target.relative_to(self.root)}")
        return 0


if __name__ == "__main__":
    raise SystemExit(DocumentationGenerationCommand(Path(__file__).resolve().parents[1]).run(tuple(sys.argv[1:])))
